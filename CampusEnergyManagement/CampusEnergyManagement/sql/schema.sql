CREATE DATABASE IF NOT EXISTS campus_energy_management;
USE campus_energy_management;

DROP TABLE IF EXISTS ENERGY_ANALYTICS;
DROP TABLE IF EXISTS REPAIR_TASK;
DROP TABLE IF EXISTS MAINTENANCE_STAFF;
DROP TABLE IF EXISTS FAULT_REPORT;
DROP TABLE IF EXISTS ENERGY_CONSUMPTION;
DROP TABLE IF EXISTS ENERGY_METER;
DROP TABLE IF EXISTS BUILDING;

CREATE TABLE BUILDING (
    Building_ID INT AUTO_INCREMENT PRIMARY KEY,
    Building_Name VARCHAR(100) NOT NULL,
    Location VARCHAR(150) NOT NULL
);

CREATE TABLE ENERGY_METER (
    Meter_ID INT AUTO_INCREMENT PRIMARY KEY,
    Building_ID INT NOT NULL,
    Meter_Type VARCHAR(50) NOT NULL,
    FOREIGN KEY (Building_ID) REFERENCES BUILDING(Building_ID) ON DELETE CASCADE
);

CREATE TABLE ENERGY_CONSUMPTION (
    Consumption_ID INT AUTO_INCREMENT PRIMARY KEY,
    Meter_ID INT NOT NULL,
    Date DATE NOT NULL,
    Units_Consumed DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (Meter_ID) REFERENCES ENERGY_METER(Meter_ID) ON DELETE CASCADE
);

CREATE TABLE FAULT_REPORT (
    Fault_ID INT AUTO_INCREMENT PRIMARY KEY,
    Building_ID INT NOT NULL,
    Description TEXT NOT NULL,
    Reported_Date DATE NOT NULL,
    Status VARCHAR(50) NOT NULL,
    FOREIGN KEY (Building_ID) REFERENCES BUILDING(Building_ID) ON DELETE CASCADE
);

CREATE TABLE MAINTENANCE_STAFF (
    Staff_ID INT AUTO_INCREMENT PRIMARY KEY,
    Staff_Name VARCHAR(100) NOT NULL,
    Phone VARCHAR(20) NOT NULL,
    Specialization VARCHAR(100) NOT NULL
);

CREATE TABLE REPAIR_TASK (
    Task_ID INT AUTO_INCREMENT PRIMARY KEY,
    Fault_ID INT NOT NULL,
    Staff_ID INT NOT NULL,
    Assignment_Date DATE NOT NULL,
    Resolution_Date DATE DEFAULT NULL,
    Repair_Status VARCHAR(50) NOT NULL,
    FOREIGN KEY (Fault_ID) REFERENCES FAULT_REPORT(Fault_ID) ON DELETE CASCADE,
    FOREIGN KEY (Staff_ID) REFERENCES MAINTENANCE_STAFF(Staff_ID) ON DELETE CASCADE
);

CREATE TABLE ENERGY_ANALYTICS (
    Analytics_ID INT AUTO_INCREMENT PRIMARY KEY,
    Building_ID INT NOT NULL,
    Month_Year VARCHAR(20) NOT NULL,
    Total_Consumption DECIMAL(12,2) NOT NULL,
    Average_Daily_Usage DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (Building_ID) REFERENCES BUILDING(Building_ID) ON DELETE CASCADE
);
